#!/usr/bin/env python3
"""Generate the service catalog from apps/*/service.yaml: platform/catalog/services.yaml (machine
readable) and docs/service-catalog.md (the catalog page people read on GitHub).

The catalog is a generated, committed file: a static, zero-cost alternative to running a developer
portal server for the MVP. CI runs `--check` so the committed catalog can never drift from the
manifests it describes.

Usage:
  scripts/generate_catalog.py            # rewrite both files
  scripts/generate_catalog.py --check    # exit 1 if either committed file is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml
from validate_service import ROOT, validate_all, with_defaults

CATALOG_PATH = ROOT / "platform" / "catalog" / "services.yaml"
PAGE_PATH = ROOT / "docs" / "service-catalog.md"
HEADER = "# GENERATED by scripts/generate_catalog.py from apps/*/service.yaml - do not edit by hand.\n"


def discover(apps_dir: Path) -> list[Path]:
    return sorted(apps_dir.glob("*/service.yaml"))


def build_catalog(manifest_paths: list[Path], root: Path = ROOT) -> dict[str, Any]:
    results = validate_all(manifest_paths)
    invalid = {p: e for p, e in results.items() if e}
    if invalid:
        lines = [f"{p}: {err}" for p, errs in invalid.items() for err in errs]
        raise ValueError("invalid manifests:\n  " + "\n  ".join(lines))

    services = []
    for path in manifest_paths:
        m = with_defaults(yaml.safe_load(path.read_text(encoding="utf-8")))
        meta, spec = m["metadata"], m["spec"]
        services.append(
            {
                "name": meta["name"],
                "owner": meta["owner"],
                "description": meta["description"],
                "tier": meta["tier"],
                "path": path.parent.resolve().relative_to(root.resolve()).as_posix(),
                "runtime": spec["runtime"],
                "port": spec["container"]["port"],
                "size": f"{spec['container']['cpu']} CPU / {spec['container']['memory']} MiB",
                "health_check": spec["healthCheck"]["path"],
                "environments": sorted(e for e, cfg in spec["environments"].items() if cfg["enabled"]),
            }
        )
    services.sort(key=lambda s: s["name"])
    return {"apiVersion": "idp.platform/v1alpha1", "kind": "ServiceCatalog", "services": services}


def render(catalog: dict[str, Any]) -> str:
    return HEADER + yaml.safe_dump(catalog, sort_keys=False, default_flow_style=False)


def render_page(catalog: dict[str, Any]) -> str:
    lines = [
        "<!-- GENERATED by scripts/generate_catalog.py from apps/*/service.yaml - do not edit by hand. -->",
        "# Service catalog",
        "",
        "Every service on the platform, generated from its validated `service.yaml`. To add one:",
        '`scripts/new_service.py <name> --owner <team> --description "..."`',
        "([developer guide](developer-guide.md#5-creating-a-new-service)).",
        "",
        "| Service | Owner | Tier | Size | Port | Health check | Environments | Description |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for s in catalog["services"]:
        envs = ", ".join(s["environments"]) or "none"
        desc = s["description"].replace("|", "\\|")
        lines.append(
            f"| [`{s['name']}`](../{s['path']}) | {s['owner']} | {s['tier']} | {s['size']} | {s['port']} "
            f"| `{s['health_check']}` | {envs} | {desc} |"
        )
    return "\n".join(lines) + "\n"


def outputs(apps_dir: Path = ROOT / "apps") -> dict[Path, str]:
    """Every generated file and its expected content."""
    catalog = build_catalog(discover(apps_dir))
    return {CATALOG_PATH: render(catalog), PAGE_PATH: render_page(catalog)}


def write_catalog(apps_dir: Path = ROOT / "apps") -> list[Path]:
    files = outputs(apps_dir)
    for path, content in files.items():
        path.write_text(content, encoding="utf-8")
    return list(files)


def _display(path: Path) -> str:
    return path.relative_to(ROOT).as_posix() if path.is_relative_to(ROOT) else str(path)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the committed catalog is out of date")
    args = parser.parse_args(argv)

    try:
        files = outputs()
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 1
    if args.check:
        stale = [p for p, c in files.items() if not p.exists() or p.read_text(encoding="utf-8") != c]
        for path in stale:
            print(f"{_display(path)} is stale: run `make catalog` and commit the result", file=sys.stderr)
        if stale:
            return 1
        print("service catalog is up to date")
        return 0
    for path, content in files.items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {_display(path)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
